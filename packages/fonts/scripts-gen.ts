// Generates src/files.gen.ts: the font files that actually exist in the Fontsource packages.
import { existsSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { FONT_CATALOG, FONT_IDS } from "@redesign/schema";
import { STATIC_WEIGHTS, SUBSETS } from "./src/spec";

const require = createRequire(import.meta.url);
const out: Record<string, string[]> = {};
for (const font of FONT_IDS) {
  const pkg = STATIC_WEIGHTS[font] ? `@fontsource/${font}` : `@fontsource-variable/${font}`;
  const dir = join(dirname(require.resolve(`${pkg}/package.json`)), "files");
  const id = FONT_CATALOG[font].file;
  out[font] = [];
  for (const subset of SUBSETS) for (const style of ["normal", "italic"]) {
    for (const w of STATIC_WEIGHTS[font] ?? ["wght"]) {
      const file = `${id}-${subset.name}-${w}-${style}.woff2`;
      if (existsSync(join(dir, file))) out[font].push(file);
    }
  }
}
writeFileSync("src/files.gen.ts", `// Generated by scripts-gen.ts. Do not edit.\nexport const AVAILABLE_FILES: Record<string, string[]> = ${JSON.stringify(out, null, 2)};\n`);
console.log("ok");
